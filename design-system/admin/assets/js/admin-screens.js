(() => {
  const slug = (name) => name.toLowerCase().replace(/[’']/g, '').replace(/\(.*?\)/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const pages = {};
  ZXA.modules.forEach((module) => module.pages.forEach(([id, name]) => {
    pages[id] = { id, name, module: module.key, file: `${module.key}/${id}-${slug(name)}.html` };
  }));
  ZXA.pages = pages;
  ZXA.page = (id) => {
    if (!pages[id]) throw new Error(`Unknown admin page ${id}`);
    return pages[id];
  };
  /* every page sits two folders down (pages/<module>/); the screen map sits at the admin root */
  const root = document.currentScript.src.replace(/assets\/js\/admin-screens\.js.*$/, '');
  ZXA.root = root;
  ZXA.href = (id, query = '') => `${root}pages/${ZXA.page(id).file}${query}`;
  ZXA.isBuilt = (id) => ZXA.built.includes(id);
})();
